-- **Three things must be true before a single statement below runs, and all
-- three are checked here rather than where they would otherwise surface.**
--
-- `pnpm db:migrate` — the documented command — wraps a migration in a
-- transaction, so a failure part-way rolls the whole thing back. But this file
-- is also the kind of thing that gets pasted into the Supabase SQL editor or run
-- with `psql -f`, and **neither of those is transactional by default**. There,
-- a failure at statement 40 leaves the first 39 applied.
--
-- That matters more here than it usually would. The statement that makes
-- `email_outbox.registration_id` nullable runs early; the check constraint that
-- keeps both addressee keys total is one of the last. A run that dies in between
-- leaves exactly the state `modules-v2.md` §3.1 calls unsurvivable — a nullable
-- key with nothing defending it, where "a row with both keys null conflicts with
-- nothing" and a double-queued digest sends twice in silence. It would not look
-- broken; it would look applied.
--
-- So every precondition is asserted up front, before anything is altered, and a
-- failure here has changed nothing at all.
do $$
declare
  v_dup_parties int;
begin
  if exists (select 1 from registration_forms) then
    raise exception
      'registration_forms is not empty, so `kind` cannot be added NOT NULL. '
      'V1 never created a form; if these rows are real, decide each one''s kind '
      'and backfill before re-running (modules-v2.md §3).';
  end if;

  if exists (select 1 from form_responses) then
    raise exception
      'form_responses is not empty, so `form_schema` cannot be added NOT NULL. '
      'Pin each response to the schema it was answered against before re-running '
      '(spec/v2.md §8.2.4).';
  end if;

  -- The one precondition that is about *data* rather than about an empty table,
  -- and therefore the one that can actually fail on a real database. The 10 Sep
  -- end-to-end pass left test registrations behind (`local.md` §5h).
  select count(*) into v_dup_parties from (
    select 1 from registrations
     where deleted_at is null and contact_email is not null
     group by segment_id, contact_email, requested_at
    having count(*) > 1) d;

  if v_dup_parties > 0 then
    raise exception
      'registrations_no_duplicate_import cannot be created: % live parties share '
      'a (segment_id, contact_email, requested_at) triple. Soft-delete the '
      'duplicates and re-run. `local.md` §4 has the query that lists them.',
      v_dup_parties;
  end if;
end
$$;--> statement-breakpoint

