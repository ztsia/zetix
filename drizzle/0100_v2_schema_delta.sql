-- 0100 — the V2 schema delta (module `J`, `docs/modules-v2.md` §3).
--
-- **Every column V2 needs is in this one migration.** It is applied to Supabase
-- by hand (`docs/local.md` §4), so a second one would mean a second manual apply
-- on concert-adjacent infrastructure; that is why the schema freezes again when
-- this branch merges (`modules-v2.md` §4).
--
-- **Numbering starts at 0100 deliberately.** `main` keeps `0007`+ free for a
-- 19 Sep hotfix, so the V1 and V2 migration lines cannot collide while `v2` is
-- open. The gap documents itself.
--
-- What it adds, and what each is for:
--
--   registrations          email_verified_at, verification_token  (v2.md §8.1.4)
--                          custom                                 (v2.md §8.2.3)
--   attendees              custom                                 (v2.md §8.2.3)
--   shows                  ends_at                                (v2.md §13.2.1)
--   registration_forms     kind, schema_version, show_id,
--                          segment_id now nullable, one-parent check
--                                                                 (v2.md §8.1, §8.2.4)
--   form_responses         form_schema, identity_key + its partial
--                          unique index, supersedes_id            (v2.md §8.2.4, §8.3)
--   feedback_responses     the table                              (v2.md §13.5)
--   email_outbox           player_id, the exactly-one-addressee check
--                          and a second partial unique index      (modules-v2.md §3.1)
--   registrations          registrations_no_duplicate_import      (import.md §9.2)
--
-- Two of the columns below are `not null` with no default, so **they require
-- their tables to be empty**: `registration_forms.kind` and
-- `form_responses.form_schema`. Both tables are empty everywhere — V1 never
-- rendered a native form, registration ran on Google Forms and arrived through
-- import (decision 9) — and there is nothing to backfill either column from. The
-- assertion below turns "column contains null values" into a sentence that says
-- what to do about it.
--
-- The tail of this file is hand-written: drizzle-kit models neither triggers nor
-- RLS, and a new table arrives with `relrowsecurity = false` and whatever
-- Supabase grants it (`drizzle/0004_lock_down_public_grants.sql`, decision 20b).

