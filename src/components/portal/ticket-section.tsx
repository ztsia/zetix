import { CircleCheckIcon, DownloadIcon, TicketIcon, UsersIcon } from 'lucide-react';
import { cn } from '@/lib/utils';
import { Badge } from '@/components/ui/badge';
import { buttonVariants } from '@/components/ui/button';
import {
  Card,
  CardAction,
  CardContent,
  CardDescription,
  CardFooter,
  CardHeader,
  CardTitle,
} from '@/components/ui/card';
import { Item, ItemContent, ItemDescription, ItemMedia, ItemTitle } from '@/components/ui/item';

/**
 * §13.3 item 1 — "Your ticket": name, code, show, the QR, and a download.
 *
 * **The segment is never shown**, here or anywhere on this surface: a guest does
 * not need to know they were in the "public" block (§13.3).
 *
 * **The ticket code is here on purpose**, though §4.1's list stops at the QR.
 * It is the door's own secondary way in (spec/tickets.md §10.1 rule 4 — the
 * scanner's Search tab takes exactly this string), and this page is what a guest
 * holds up when the QR will not read off their screen. It is their own
 * identifier and discloses nothing further.
 */
export function TicketSection({
  name,
  ticketCode,
  qr,
  admitted,
  admittedAt,
  downloadHref,
  pastNote,
  partySize = 1,
}: {
  name: string;
  ticketCode: string | null;
  /**
   * The QR's markup, or null when the page must not offer it: the show's day
   * has passed and this seat was never admitted (spec/v3.md §32.3).
   */
  qr: string | null;
  admitted: boolean;
  admittedAt: string | null;
  /** Null until a ticket has actually been issued: there is no PDF to give. */
  downloadHref: string | null;
  /** What to say instead of "Present this QR" once the show's day is over. */
  pastNote?: string | null;
  /**
   * Seats in this holder's booking — a count, nobody named (spec/v3.md §32.4).
   * Each seat keeps its own link; this page only says it is one of them.
   */
  partySize?: number;
}) {
  const party = partySize > 1 && !admitted && !pastNote;
  return (
    <Card>
      <CardHeader>
        <CardTitle role="heading" aria-level={2} className="text-xl text-balance">
          {name}
        </CardTitle>
        <CardDescription>
          {admitted
            ? admittedAt
              ? `Admitted ${admittedAt}`
              : 'Already admitted'
            : (pastNote ?? 'Present this QR at the door')}
        </CardDescription>
        {admitted ? (
          <CardAction>
            <Badge variant="secondary">
              <CircleCheckIcon data-icon="inline-start" />
              Checked in
            </Badge>
          </CardAction>
        ) : partySize > 1 ? (
          <CardAction>
            <Badge variant="outline">
              <UsersIcon data-icon="inline-start" />
              {partySize} seats
            </Badge>
          </CardAction>
        ) : null}
      </CardHeader>
      <CardContent className="flex flex-col items-center gap-3">
        {/*
         * **Always light, never themed.** The symbol ships its own opaque white
         * background path, and the padding around it extends that plate so the
         * quiet zone survives on a dark page. This is spec/tickets.md §10.4's
         * rendering constraint applied to a screen: a QR on a dark surface is a
         * QR that does not scan.
         *
         * The markup is generated by `qrcode` from our own origin and a
         * shape-checked base62 token, and is checked to be an `<svg>` element
         * before it gets here (`src/lib/portal/qr.ts`). It is named as one
         * image, so a screen reader says what it is rather than nothing.
         */}
        {qr ? (
          <div
            role="img"
            aria-label={ticketCode ? `QR code for ticket ${ticketCode}` : 'Your ticket QR code'}
            className="w-full max-w-64 rounded-xl bg-white p-3 [&>svg]:block [&>svg]:h-auto [&>svg]:w-full"
            dangerouslySetInnerHTML={{ __html: qr }}
          />
        ) : null}
        {ticketCode ? (
          <div className="flex flex-col items-center gap-0.5">
            {/* An usher asks for "your code" when a QR will not read. */}
            <span className="text-muted-foreground text-xs">Ticket code</span>
            <span className="font-mono text-lg tracking-[0.2em] tabular-nums">{ticketCode}</span>
          </div>
        ) : null}
        {party ? (
          <p className="text-muted-foreground text-center text-sm text-balance">
            This is one of {partySize} seats in your booking, each with its own code. Arriving
            together? The usher can check in the whole party from any one of them.
          </p>
        ) : null}
      </CardContent>
      <CardFooter>
        {downloadHref ? (
          /**
           * **The PDF is the ticket** (§13.1), so the portal always offers a route
           * back to it once it exists.
           *
           * A real anchor, styled as a button, so long-press, "open in new tab"
           * and a screen reader's link list all work — a `Button` rendering an
           * `<a>` was announced as a button. 48px tall, a tap target for a thumb
           * outdoors (spec/v3.md §32.3). A plain `<a>` rather than `next/link`:
           * the file is served by a Route Handler, so there is no route to
           * prefetch.
           */
          <a
            href={`${downloadHref}?download=1`}
            className={cn(buttonVariants({ variant: 'outline', size: 'lg' }), 'h-12 w-full text-base')}
          >
            <DownloadIcon data-icon="inline-start" />
            Download your ticket (PDF)
          </a>
        ) : (
          <p className="text-muted-foreground text-sm">
            Your PDF ticket is on its way by email. This page will offer it as soon as it is
            issued.
          </p>
        )}
      </CardFooter>
    </Card>
  );
}

/**
 * The same ticket, collapsed once the show is over (§13.2, third row).
 *
 * **What survives the collapse is the admission record**, not the QR. The
 * evening is done and the code admits nobody now; what a guest might still want
 * from this page is confirmation that they were let in, and their name on it so
 * the page is recognisably theirs. The download stays for the same reason the
 * full card carries it — the PDF is the ticket, and people keep tickets.
 */
export function TicketStub({
  name,
  admitted,
  admittedAt,
  downloadHref,
}: {
  name: string;
  admitted: boolean;
  admittedAt: string | null;
  downloadHref: string | null;
}) {
  return (
    <Item
      variant="muted"
      render={
        downloadHref ? (
          <a href={downloadHref} target="_blank" rel="noreferrer noopener" />
        ) : undefined
      }
    >
      <ItemMedia variant="icon">
        {admitted ? <CircleCheckIcon /> : <TicketIcon />}
      </ItemMedia>
      <ItemContent>
        <ItemTitle className="text-base">{name}</ItemTitle>
        <ItemDescription>
          {admitted && admittedAt ? `Admitted ${admittedAt}` : 'Your ticket'}
        </ItemDescription>
      </ItemContent>
      {downloadHref ? <DownloadIcon className="size-4 text-muted-foreground" /> : null}
    </Item>
  );
}
