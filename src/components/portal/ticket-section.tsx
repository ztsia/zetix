import { CircleCheckIcon, DownloadIcon } from 'lucide-react';
import { Badge } from '@/components/ui/badge';
import { Button } from '@/components/ui/button';
import {
  Card,
  CardAction,
  CardContent,
  CardDescription,
  CardFooter,
  CardHeader,
  CardTitle,
} from '@/components/ui/card';
import { Item, ItemContent, ItemDescription, ItemMedia, ItemTitle } from '@/components/ui/item';

/**
 * §13.3 item 1 — "Your ticket": name, code, show, the QR, and a download.
 *
 * **The segment is never shown**, here or anywhere on this surface: a guest does
 * not need to know they were in the "public" block (§13.3).
 *
 * **The ticket code is here on purpose**, though §4.1's list stops at the QR.
 * It is the door's own secondary way in (spec/tickets.md §10.1 rule 4 — the
 * scanner's Search tab takes exactly this string), and this page is what a guest
 * holds up when the QR will not read off their screen. It is their own
 * identifier and discloses nothing further.
 */
export function TicketSection({
  name,
  ticketCode,
  qr,
  admitted,
  admittedAt,
  downloadHref,
}: {
  name: string;
  ticketCode: string | null;
  qr: string;
  admitted: boolean;
  admittedAt: string | null;
  downloadHref: string;
}) {
  return (
    <Card>
      <CardHeader>
        <CardTitle className="text-xl text-balance">{name}</CardTitle>
        <CardDescription>
          {admitted
            ? admittedAt
              ? `Admitted ${admittedAt}`
              : 'Already admitted'
            : 'Present this QR at the door'}
        </CardDescription>
        {admitted ? (
          <CardAction>
            <Badge variant="secondary">
              <CircleCheckIcon data-icon="inline-start" />
              Checked in
            </Badge>
          </CardAction>
        ) : null}
      </CardHeader>
      <CardContent className="flex flex-col items-center gap-3">
        {/*
         * **Always light, never themed.** The symbol ships its own opaque white
         * background path, and the padding around it extends that plate so the
         * quiet zone survives on a dark page. This is spec/tickets.md §10.4's
         * rendering constraint applied to a screen: a QR on a dark surface is a
         * QR that does not scan.
         *
         * The markup is generated by `qrcode` from our own origin and a
         * shape-checked base62 token, and is checked to be an `<svg>` element
         * before it gets here (`src/lib/portal/qr.ts`).
         */}
        <div
          className="w-full max-w-64 rounded-xl bg-white p-3 [&>svg]:block [&>svg]:h-auto [&>svg]:w-full"
          dangerouslySetInnerHTML={{ __html: qr }}
        />
        {ticketCode ? (
          <p className="font-mono text-lg tracking-[0.2em] tabular-nums">{ticketCode}</p>
        ) : null}
      </CardContent>
      <CardFooter>
        {/*
         * **The PDF is the ticket** (§13.1), so the portal always offers a route
         * back to it — a guest whose email is buried can still reach the
         * document of record from the QR they scanned.
         *
         * `render` because this is navigation, not an action: it must be a real
         * anchor so that long-press, "open in new tab" and a screen reader's
         * link list all work. A plain `<a>` rather than `next/link` — the file
         * is served by a Route Handler, so there is no route to prefetch and a
         * client-side navigation would be the wrong thing entirely.
         */}
        <Button
          variant="outline"
          size="lg"
          className="w-full"
          render={<a href={downloadHref} target="_blank" rel="noreferrer noopener" />}
        >
          <DownloadIcon data-icon="inline-start" />
          Download your ticket
        </Button>
      </CardFooter>
    </Card>
  );
}

/**
 * The same ticket, collapsed once the show is over (§13.2, third row).
 *
 * **What survives the collapse is the admission record**, not the QR. The
 * evening is done and the code admits nobody now; what a guest might still want
 * from this page is confirmation that they were let in, and their name on it so
 * the page is recognisably theirs. The download stays for the same reason the
 * full card carries it — the PDF is the ticket, and people keep tickets.
 */
export function TicketStub({
  name,
  admitted,
  admittedAt,
  downloadHref,
}: {
  name: string;
  admitted: boolean;
  admittedAt: string | null;
  downloadHref: string;
}) {
  return (
    <Item variant="muted" render={<a href={downloadHref} target="_blank" rel="noreferrer noopener" />}>
      <ItemMedia variant="icon">
        {admitted ? <CircleCheckIcon /> : <DownloadIcon />}
      </ItemMedia>
      <ItemContent>
        <ItemTitle className="text-base">{name}</ItemTitle>
        <ItemDescription>
          {admitted && admittedAt ? `Admitted ${admittedAt}` : 'Your ticket'}
        </ItemDescription>
      </ItemContent>
      <DownloadIcon className="size-4 text-muted-foreground" />
    </Item>
  );
}
